/* Verify user feedback through actual controls and rendered headgear. */
const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
 const out=path.resolve(__dirname,'../build/ui-feedback');fs.mkdirSync(out,{recursive:true});
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 try{
  const page=await browser.newPage({acceptDownloads:true,viewport:{width:1440,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.VRM2SKYRIM_TEST_URL||'http://127.0.0.1:8791');
  await page.waitForFunction(()=>document.querySelector('#game').value.length>0);
  await page.locator('#source').setInputFiles(process.env.VRM2SKYRIM_TEST_VRM);
  await page.waitForFunction(()=>document.querySelector('#source-status').textContent.includes('三角形'));
  await page.locator('#armor_support').selectOption('true');
  assert.equal(await page.locator('#wardrobe-add').textContent(),'＋ 衣服を追加');
  assert.match(await page.locator('.reset-help').textContent(),/手動/);
  await page.locator('#wardrobe-split').click();
  const clothing=page.locator('.wardrobe-item');assert.ok(await clothing.count()>1);
  const first=clothing.first();await first.locator('summary').click();
  assert.equal(await first.locator('[data-field="slot"]').inputValue(),'auto');
  await first.locator('[data-field="item_kind"]').selectOption('hands');
  assert.match(await first.locator('[data-field="slot"] option[value="auto"]').textContent(),/33/);
  await first.locator('[data-field="item_kind"]').selectOption('body');
  await first.locator('[data-field="slot"]').selectOption('32');
  assert.equal(await first.locator('[data-field="slot"] option[value="42"]').count(),1);
  await page.locator('#fit-enabled').check();
  await page.locator('#fit_mode').selectOption('all_official');
  await page.locator('#fit_source').selectOption('official');
  await page.locator('#fit-panel details summary').click();
  assert.equal(await page.locator('#head-policies [data-addon]').count(),1);
  assert.match(await page.locator('#head-hide-face').locator('..').textContent(),/全体デフォルト設定/);
  await page.locator('#head-search').fill('IronHelmet');
  const card=page.locator('#head-policies [data-addon]');
  assert.equal(await card.count(),1);
  await card.locator('[data-policy="hide_hair"]').uncheck();
  await card.getByRole('button',{name:'リセット',exact:true}).click();
  assert.ok(await card.locator('[data-policy="hide_hair"]').isChecked());
  const jobResponse=page.waitForResponse(r=>r.url().endsWith('/api/head-preview'));
  await page.locator('#head-preview').click();
  const result=await(await jobResponse).json();assert.ok(result.job_id,JSON.stringify(result));
  console.log('Head preview button started job',result.job_id);
  await page.waitForFunction(()=>document.querySelector('#head-preview-images img')||!document.querySelector('#error').hidden,{},{timeout:600000});
  if(await page.locator('#error').isVisible())throw Error(await page.locator('#error').textContent());
  await page.waitForFunction(()=>document.querySelector('#head-preview-images img').naturalWidth>0);
  const job=await(await page.request.get(new URL('/api/jobs/'+result.job_id,page.url()).href)).json();
  fs.writeFileSync(path.join(out,'head-job.json'),JSON.stringify(job,null,2));
  await page.locator('#head-preview-images').screenshot({path:path.join(out,'head-preview.png')});
  assert.match(fs.readFileSync(path.join(job.output,'previews/wardrobe-armor-ArmorIronHelmet-rest.json'),'utf8'),/face.nif/);
  await card.locator('[data-policy="hide_face"]').check();
  await card.locator('[data-policy="hide_hair"]').uncheck();
  const second=page.waitForResponse(r=>r.url().endsWith('/api/head-preview'));
  await page.locator('#head-preview').click();const secondResult=await(await second).json();
  await page.waitForFunction(()=>document.querySelector('#head-preview-images img')||!document.querySelector('#error').hidden,{},{timeout:120000});
  if(await page.locator('#error').isVisible())throw Error(await page.locator('#error').textContent());
  const secondJob=await(await page.request.get(new URL('/api/jobs/'+secondResult.job_id,page.url()).href)).json();
  assert.equal(secondJob.output,job.output,'Visibility-only changes reuse the fitted geometry');
  const description=JSON.parse(fs.readFileSync(path.join(secondJob.output,'previews/wardrobe-armor-ArmorIronHelmet-rest.json'),'utf8'));
  assert.ok(description.nifs.some(n=>n.endsWith('hair.nif')));
  assert.ok(!description.nifs.some(n=>n.endsWith('face.nif')));
  await page.locator('#next').click();await page.locator('#next').click();
  assert.match(await page.locator('#combat_class option[value="Blade"]').textContent(),/ブレイズ/);
  await page.locator('#next').click();
  await page.locator('#spell-search').fill('AbWolfIce');assert.equal(await page.locator('#spells input').count(),0);
  await page.locator('#spell-search').fill('AltarAkatoshSpell');assert.equal(await page.locator('#spells input').count(),0);
  await page.locator('#spell-search').fill('Firebolt');assert.ok(await page.locator('#spells input').count()>0);
  await page.locator('#next').click();
  const event=page.waitForEvent('download');await page.locator('#export-settings').click();
  await(await event).saveAs(path.join(out,'settings.json'));
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('Automatic / standard slots, compact head settings, real fitted preview, class and spell filtering PASS');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
