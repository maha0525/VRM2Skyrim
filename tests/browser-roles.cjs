/* Isolated UI checks with a read-only game catalog fixture; never starts a conversion. */
const {chromium}=require('playwright');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),fixture=path.resolve(process.argv[2]||'build/ui-roles');
const defaults=JSON.parse(fs.readFileSync(path.join(fixture,'defaults.json')));
const choices=JSON.parse(fs.readFileSync(path.join(fixture,'roles.json')));
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 try{
  const page=await browser.newPage({acceptDownloads:true,viewport:{width:1440,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',async route=>{
   const request=route.request(),url=new URL(request.url());let data;
   if(url.pathname==='/api/environment')data={defaults,game:'Read-only fixture',blender:'Fixture Blender',version:'test'};
   else if(url.pathname==='/api/jobs')data={jobs:[]};
   else if(url.pathname==='/api/source')data={source_id:'fixture',sha256:'fixture',filename:'fixture.vrm',mesh_count:1,triangles:1,suggested_name:'Test',parts:[]};
   else if(url.pathname==='/api/catalog')data={checks:{ready:true},choices:{...choices,armors:[],equipment_plugins:[]}};
   else if(url.pathname==='/api/validate')data={settings:request.postDataJSON().settings};
   if(data!==undefined)return route.fulfill({json:data});
   const name=url.pathname==='/'?'index.html':url.pathname.slice(1),file=path.join(root,'web',name);
   if(!fs.existsSync(file))return route.fulfill({status:404,body:'not found'});
   return route.fulfill({body:fs.readFileSync(file),contentType:name.endsWith('.js')?'application/javascript':name.endsWith('.css')?'text/css':'text/html'});
  });
  await page.goto('http://127.0.0.1:8899/');
  await page.waitForFunction(()=>document.querySelector('#game').value.length>0);
  await page.locator('#source').setInputFiles({name:'fixture.vrm',mimeType:'application/octet-stream',buffer:Buffer.from('fixture')});
  await page.waitForFunction(()=>document.querySelector('#source-status').textContent.includes('三角形'));
  await page.locator('#next').click();await page.locator('[data-step="1"]').waitFor({state:'visible'});
  await page.locator('#next').click();await page.locator('[data-step="2"]').waitFor({state:'visible'});
  assert.equal(await page.locator('#protection').inputValue(),'essential');
  assert.equal(await page.locator('#morality').inputValue(),'0');
  await page.locator('#sitting-settings summary').click();
  assert.equal(await page.locator('#sitting_enabled').isChecked(),true);
  assert.equal(await page.locator('#sitting_auto').isChecked(),true);
  await page.locator('#sitting_offset').fill('2.5');
  assert.match(await page.locator('#class-details').textContent(),/片手武器 3/);
  assert.match(await page.locator('#class-details').textContent(),/体力 4：マジカ 0：スタミナ 2/);
  assert.equal(await page.locator('#combat_style option[value="csMammoth"]').count(),0);
  assert.equal(await page.locator('#combat_style option').count(),choices.styles.filter(x=>x.humanoid).length);
  await page.locator('#all-styles').check();await page.locator('#combat_style').selectOption('csMammoth');
  assert.ok((await page.locator('#style-details').textContent()).includes(choices.styles.find(x=>x.id==='csMammoth').used_by[0]));
  await page.locator('#all-styles').uncheck();
  assert.equal(await page.locator('#combat_style').inputValue(),defaults.combat_style);
  await page.locator('#preset').selectOption('mage');
  assert.equal(await page.locator('#combat_class').inputValue(),'CombatMageDestruction');
  assert.match(await page.locator('#class-details').textContent(),/破壊 3/);
  await page.locator('#combat_class').selectOption('CombatWarrior1H');
  assert.match(await page.locator('#class-details').textContent(),/片手武器 3/);
  await page.locator('#manual-skills summary').click();
  assert.equal(await page.locator('#skill-OneHanded').isDisabled(),true);
  await page.locator('#use-manual-skills').click();
  assert.equal(await page.locator('#auto_calculate').inputValue(),'false');
  assert.equal(await page.locator('#skills input').count(),18);
  await page.locator('#skill-OneHanded').fill('75');await page.locator('#skill-Destruction').fill('92');
  await page.screenshot({path:path.join(fixture,'roles-step03.png'),fullPage:true});
  await page.locator('#next').click();await page.locator('[data-step="3"]').waitFor({state:'visible'});
  await page.locator('#perk-search').fill('Armsman00');
  await page.locator('#perks input[data-record-id="Armsman00"]').check();
  await page.locator('#next').click();await page.locator('[data-step="4"]').waitFor({state:'visible'});
  const downloadPromise=page.waitForEvent('download');await page.locator('#export-settings').click();
  const download=await downloadPromise,exported=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
  assert.equal(exported.skills.OneHanded,75);assert.equal(exported.skills.Destruction,92);
  assert.equal(Object.keys(exported.skills).length,18);
  assert.deepEqual(exported.perks,[{editor_id:'Armsman00',rank:0}]);
  assert.equal(exported.protection,'essential');assert.equal(exported.morality,0);
  assert.equal(exported.sitting_enabled,true);assert.equal(exported.sitting_auto,true);
  assert.equal(exported.sitting_offset,2.5);
  for(let step=3;step>=0;step--){await page.locator('#back').click();await page.locator(`[data-step="${step}"]`).waitFor({state:'visible'});}
  const imported={...exported,protection:'protected',morality:3,combat_style:'csMammoth',sitting_auto:false,sitting_offset:-1.5};
  await page.locator('#import-settings').setInputFiles({name:'previous-settings.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(imported))});
  await page.waitForFunction(()=>document.querySelector('#import-status').textContent.includes('読み込みました'));
  await page.locator('#next').click();await page.locator('[data-step="1"]').waitFor({state:'visible'});
  await page.locator('#next').click();await page.locator('[data-step="2"]').waitFor({state:'visible'});
  assert.equal(await page.locator('#combat_style').inputValue(),'csMammoth');
  assert.equal(await page.locator('#all-styles').isChecked(),true);
  assert.equal(await page.locator('#protection').inputValue(),'protected');assert.equal(await page.locator('#morality').inputValue(),'3');
  assert.equal(await page.locator('#skill-OneHanded').inputValue(),'75');
  assert.equal(await page.locator('#sitting_auto').isChecked(),false);
  assert.equal(await page.locator('#sitting_offset').inputValue(),'-1.5');
  await page.locator('#auto_calculate').selectOption('true');
  assert.equal(await page.locator('#skill-OneHanded').isDisabled(),true);
  await page.locator('#next').click();await page.locator('[data-step="3"]').waitFor({state:'visible'});
  await page.locator('#next').click();await page.locator('[data-step="4"]').waitFor({state:'visible'});
  const autoDownloadPromise=page.waitForEvent('download');await page.locator('#export-settings').click();
  const autoDownload=await autoDownloadPromise,automatic=JSON.parse(fs.readFileSync(await autoDownload.path(),'utf8'));
  assert.deepEqual(automatic.skills,{});assert.deepEqual(automatic.perks,exported.perks);
  assert.equal(automatic.sitting_auto,false);assert.equal(automatic.sitting_offset,-1.5);
  assert.deepEqual(errors,[]);
  console.log('PASS: class/preset details, humanoid filter, all-styles, manual 18 skills, Perks, new defaults, export/reimport preservation and automatic-mode export');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
