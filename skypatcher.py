"""Follower-owned SkyPatcher rules: no aggregate ESP or cross-follower masters."""

import configparser
import json
import logging
from pathlib import Path
import struct

from follower_plugin import follower_records
from gear_head_runtime import IDS
from official_catalog import OfficialCatalog
from settings import load_settings


def config_paths(plugin):
    return {
        kind: Path("SKSE/Plugins/SkyPatcher") / kind / "VRM2Skyrim" / (plugin + ".ini")
        for kind in ("armor", "formList")
    }


def rules(profile):
    plugin = profile["plugin"]
    armor, lists = set(), set()
    for item in profile["equipment"]:
        owner = item.get("origin_plugin", "Skyrim.esm")
        local = item.get("origin_local_id", item["original_form_id"] & 0xFFFFFF)
        original = f"{owner}|{local:06X}"
        addon = f"{plugin}|{item['addon_local_id']:06X}"
        armor.add(
            f"hasPlugins={plugin},{owner}:filterByArmors={original}:"
            f"filterByArmorAddonsExcluded={addon}:armorAddonsToAdd={addon}"
        )
        for flag, name in (
            ("hide_face", "FaceHidingEquipment"),
            ("hide_hair", "HairHidingEquipment"),
        ):
            if item.get(flag):
                lists.add(
                    f"filterByFormLists={plugin}|{IDS[name] & 0xFFFFFF:06X}:formsToAdd={original}"
                )
    # Filename is EXACTLY <follower ESP>.ini: both SkyPatcher readers skip the
    # whole file when that plugin is not loaded (formList has no hasPlugins key).
    return {"armor": sorted(armor), "formList": sorted(lists)}


def footstep_bindings(game_data, profile, owners=(), catalog=None):
    """Follower masters and SNDD references; owners adds other referenced plugins (shouts)
    so every reference is numbered against the same combined master order."""
    catalog = catalog or OfficialCatalog(game_data)
    bindings = {}
    needed = set()
    for item in profile["equipment"]:
        if not item.get("source_addon_key"):
            continue
        addon = catalog.require(item["source_addon_key"], b"ARMA")
        for blob in addon.values(b"SNDD"):
            value = struct.unpack("<I", blob)[0]
            if not value:
                continue
            owner = catalog.plugins[value >> 24]
            binding = (owner, value & 0xFFFFFF)
            old = bindings.setdefault(item["addon_local_id"], binding)
            if old != binding:
                raise ValueError("Shared fitted addon has conflicting footstep sounds")
            needed.add(owner)
    extras = catalog.extra_masters(needed | set(owners))
    refs = {
        addon: (0 if owner == "Skyrim.esm" else extras.index(owner) + 2) << 24 | local
        for addon, (owner, local) in bindings.items()
    }
    return extras, refs


def write_registration(output):
    output = Path(output)
    settings = load_settings(output)
    profile = json.loads((output / "armor-fitting.json").read_text(encoding="utf8"))
    if profile["plugin"] != settings.plugin_name:
        raise ValueError("Armor registration belongs to a different follower")
    counts = {}
    for kind, lines in rules(profile).items():
        path = output / "mod" / config_paths(settings.plugin_name)[kind]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            "; Generated by VRM2Skyrim; owned by "
            + settings.plugin_name
            + "\n"
            + "\n".join(lines)
            + "\n",
            encoding="utf8",
        )
        counts[kind] = len(lines)
    report = dict(
        mode="skypatcher",
        plugin=settings.plugin_name,
        rules=counts,
        configs={
            k: p.as_posix() for k, p in config_paths(settings.plugin_name).items()
        },
    )
    (output / "armor-registration.json").write_text(
        json.dumps(report, indent=2), encoding="utf8"
    )
    logging.info(
        "Follower-owned armor registration: %s, armor rules=%s, visibility rules=%s",
        settings.plugin_name,
        counts["armor"],
        counts["formList"],
    )
    return report


def validate_registration(output):
    output = Path(output)
    settings = load_settings(output)
    profile = json.loads((output / "armor-fitting.json").read_text(encoding="utf8"))
    if profile["plugin"] != settings.plugin_name:
        raise ValueError("Armor registration belongs to a different follower")
    expected = rules(profile)
    for kind, lines in expected.items():
        path = output / "mod" / config_paths(settings.plugin_name)[kind]
        observed = [
            line
            for line in path.read_text(encoding="utf8").splitlines()
            if line and not line.startswith(";")
        ]
        if observed != lines:
            raise ValueError(
                "SkyPatcher registration differs from fitted equipment: " + kind
            )
    parsed = follower_records(output / "mod" / settings.plugin_name)
    addons = {r.form_id & 0xFFFFFF: r for r in parsed if r.kind == b"ARMA"}
    for item in profile["equipment"]:
        addon = addons.get(item["addon_local_id"])
        if addon is None or addon.values(b"RNAM") != [struct.pack("<I", 0x01000804)]:
            raise ValueError("Registered addon is missing or uses another race")
    for name in ("FaceHidingEquipment", "HairHidingEquipment"):
        listing = next((r for r in parsed if r.form_id == IDS[name]), None)
        if listing and any(
            struct.unpack("<I", value)[0] >> 24 != 1
            for value in listing.values(b"LNAM")
        ):
            raise ValueError("Fitted headgear must be registered only by SkyPatcher")
    if (output / "mod/VRM2SkyrimArmorPatch.esp").exists():
        raise ValueError(
            "Follower ZIP must not include the legacy aggregate armor patch"
        )
    logging.info(
        "Validated independent registration for %s (%s equipment bindings)",
        settings.plugin_name,
        len(profile["equipment"]),
    )
    return dict(mode="skypatcher", bindings=len(profile["equipment"]))


def installation_status(game_data, plugin=None, expected_output=None):
    data = Path(game_data)
    dll = data / "SKSE/Plugins/SkyPatcher.dll"
    config = configparser.ConfigParser()
    ini = data / "SKSE/Plugins/SkyPatcher.ini"
    problems = []
    if not dll.is_file():
        problems.append("missing_runtime")
    else:
        blob = dll.read_bytes()
        if any(
            key not in blob
            for key in (
                b"armorAddonsToAdd",
                b"filterByArmorAddonsExcluded",
                b"hasPlugins",
                b"formsToAdd",
            )
        ):
            problems.append("unsupported_runtime")
    try:
        config.read(ini, encoding="utf-8-sig")
    except (configparser.Error, UnicodeError):
        problems.append("invalid_config")
    for key in ("iEnableArmorPatching", "iEnableFormlistPatching"):
        try:
            enabled = config.getint("Patcher", key, fallback=0)
        except ValueError:
            enabled = 0
        if enabled != 1 and dll.is_file():
            problems.append(key)
    if plugin:
        if not (data / plugin).is_file():
            problems.append("missing_follower")
        for path in config_paths(plugin).values():
            installed = data / path
            if not installed.is_file():
                if "missing_config" not in problems:
                    problems.append("missing_config")
            elif expected_output:
                expected = Path(expected_output) / "mod" / path
                if (
                    expected.is_file()
                    and installed.read_bytes() != expected.read_bytes()
                ):
                    if "outdated_config" not in problems:
                        problems.append("outdated_config")
    logging.info(
        "SkyPatcher installation check: follower=%s problems=%s legacy_patch=%s",
        plugin,
        problems,
        (data / "VRM2SkyrimArmorPatch.esp").is_file(),
    )
    return dict(
        ready=not problems,
        problems=problems,
        legacy_patch=(data / "VRM2SkyrimArmorPatch.esp").is_file(),
    )
